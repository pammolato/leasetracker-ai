export type OccupancyStatus = "Occupied" | "Vacant";

export type RenewalStatus = "Not Yet Due" | "Pending";

export type LeaseStatus = "Active" | "Expired";

export type PaymentStatus = "Paid" | "Partially Paid" | "Unpaid" | "Rent Free";

export interface Payment {
  paymentId: string;
  billingMonth: string;
  dueDate: string;
  basicRentDue: number;
  vatDue: number;
  basicCusaDue: number;
  cusaVatDue: number;
  cwtDeduction: number;
  expectedCash: number;
  amountPaid: number | null;
  paymentDate: string | null;
  paymentStatus: PaymentStatus;
  notes: string | null;
}

export interface Lease {
  leaseId: string;
  propertyId: string;
  unitId: string;
  tenantName: string;
  leaseStartDate: string;
  leaseExpirationDate: string;
  basicMonthlyRent: number;
  rentDueDay: number;
  vatApplicable: boolean;
  vatRate: number | null;
  cwtApplicable: boolean;
  cwtRate: number | null;
  cusaApplicable: boolean;
  cusaVatApplicable: boolean;
  cusaVatRate: number | null;
  monthlyCusaAmount: number | null;
  escalationApplicable: boolean;
  escalationRate: number | null;
  escalationEffectiveDate: string | null;
  escalationFrequency: string | null;
  securityDeposit: number;
  renewalStatus: RenewalStatus;
  leaseStatus: LeaseStatus;
  payments: Payment[];
}

export interface Unit {
  unitId: string;
  propertyId: string;
  unitNumber: string;
  floorAreaSqm: number;
  occupancyStatus: OccupancyStatus;
  lease: Lease | null;
}

